#!/usr/bin/env python3
"""Regenerate exact Go 1.27.1 Unicode 17 regex tables using the existing toolchain."""
import argparse
import json
import os
from pathlib import Path
import shlex
import subprocess

from build import directory

HERE = Path(__file__).resolve().parent


def generate(mod_cache):
    root = directory(HERE.parent.parent)
    destination = directory(root / "src/crates/promql-engine/src/frontend") / "regex_unicode.rs"
    command = ["go", "run", str(HERE / "capture/regex_unicode.go")]
    env = os.environ.copy()
    env.update(GOTOOLCHAIN="local", GOPROXY="off", GOSUMDB="off", GOWORK="off",
               GOMODCACHE=str(directory(mod_cache)), GOCACHE=str(directory(HERE / ".tmp") / "go-build"),
               GOFLAGS="-mod=readonly")
    print(f"{HERE} > {shlex.join(command)}", flush=True)
    result = subprocess.run(command, cwd=HERE, env=env, capture_output=True, timeout=600)
    if result.returncode:
        raise RuntimeError(f"command failed ({result.returncode}): {result.stderr.decode(errors='replace')}")
    data = json.loads(result.stdout)
    if (data["go_version"], data["unicode_version"]) != ("go1.27.1", "17.0.0"):
        raise ValueError("unexpected Unicode data version")
    lines = ["// SPDX-License-Identifier: GPL-3.0-or-later",
             "// Generated by tests/promql-conformance/regex_unicode.py; Go 1.27.1 / Unicode 17.0.0.",
             "// Derived from Go unicode tables; see NOTICE.",
             "pub type Table = &'static [(u32, u32, u32)];"]
    for field in ("categories", "scripts", "fold_categories", "fold_scripts"):
        lines.append(f"pub const {field.upper()}: &[(&str, Table)] = &[")
        for table in data[field]:
            lines.append(f'    ("{table["name"]}", &[')
            for lo, hi, stride in table["ranges"]:
                lines.append(f"        (0x{lo:x}, 0x{hi:x}, {stride}),")
            lines.append("    ]),")
        lines.append("];")
    lines.append("pub const SIMPLE_FOLD: &[(u32, u32)] = &[")
    for left, right in data["simple_fold"]:
        lines.append(f"    (0x{left:x}, 0x{right:x}),")
    lines.append("];")
    lines.append("pub const LOWER: &[(u32, u32)] = &[")
    for left, right in data["lower"]:
        lines.append(f"    (0x{left:x}, 0x{right:x}),")
    lines.append("];")
    lines.append("pub const CATEGORY_ALIASES: &[(&str, &str)] = &[")
    for name, category in sorted(data["category_aliases"].items()):
        lines.append(f"    ({json.dumps(name)}, {json.dumps(category)}),")
    lines.append("];")
    destination.write_text("\n".join(lines)+"\n")
    command = ["go", "run", str(HERE / "capture/regex_normalization.go")]
    print(f"{HERE / 'oracle'} > {shlex.join(command)}", flush=True)
    result = subprocess.run(command, cwd=directory(HERE / "oracle"), env=env, capture_output=True, timeout=600)
    if result.returncode:
        raise RuntimeError(f"command failed ({result.returncode}): {result.stderr.decode(errors='replace')}")
    normalization = json.loads(result.stdout)
    if (normalization["go_version"], normalization["unicode_version"], normalization["norm_version"]) != (
            "go1.27.1", "17.0.0", "17.0.0"):
        raise ValueError("unexpected normalization version")
    lines = ["// SPDX-License-Identifier: GPL-3.0-or-later",
             "// Generated by tests/promql-conformance/regex_unicode.py; pinned x/text v0.41.0.",
             "// Derived from Go Unicode 17 NFKD data; see NOTICE.",
             "pub type Entry = (u32, u8, u8, u8, &'static [u32]);",
             "pub const NFKD: &[Entry] = &["]
    for row in normalization["entries"]:
        decomposed = ", ".join(f"0x{v:x}" for v in row["decomposition"])
        lines.append(f'    (0x{row["rune"]:x}, {row["ccc"]}, {row["leading"]}, {row["trailing"]}, &[{decomposed}]),')
    lines.append("];")
    (destination.parent / "regex_normalization_data.rs").write_text("\n".join(lines)+"\n")
    print(json.dumps({"categories": len(data["categories"]), "scripts": len(data["scripts"]),
                      "simple_fold": len(data["simple_fold"]), "lower": len(data["lower"]),
                      "normalization_entries": len(normalization["entries"])}))


if __name__ == "__main__":
    cli = argparse.ArgumentParser(description=__doc__)
    cli.add_argument("--mod-cache", required=True, help="existing pinned Go module cache; downloads disabled")
    generate(cli.parse_args().mod_cache)
